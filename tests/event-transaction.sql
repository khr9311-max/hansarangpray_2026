begin;
set local role service_role;
do $$ declare v bigint;
pid uuid;
rid uuid;
gcount int;
before_members jsonb;
after_members jsonb;
payload jsonb;
begin select revision into v from public.match_control;
select jsonb_build_object('target',4,'mode','team','confirm','재편성','assignments',jsonb_agg(jsonb_build_object('participant_id',id,'group_number',1+(rn-1)/4))) into payload from (select id,row_number() over(order by id) rn from public.participants) p;
perform public.prayer_command(v,'publish',payload);
select id into rid from public.match_rounds where is_active;
select count(*) into gcount from public.match_groups where round_id=rid;
select jsonb_agg(to_jsonb(m) order by m.participant_id) into before_members from public.match_members m join public.match_groups g on g.id=m.group_id where g.round_id=rid;
for i in 1..20 loop pid:=public.prayer_register('검증용','전도팀','검증용');
end loop;
if (select count(*) from public.match_groups where round_id=rid) <> gcount then raise exception 'New group created';
end if;
select jsonb_agg(to_jsonb(m) order by m.participant_id) into after_members from public.match_members m join public.match_groups g on g.id=m.group_id where g.round_id=rid and m.participant_id in (select (x->>'participant_id')::uuid from jsonb_array_elements(before_members) x);
if before_members is distinct from after_members then raise exception 'Existing member moved';
end if;
perform public.prayer_edit(pid,0,'수정검증','운영팀','수정검증');
begin perform public.prayer_edit(pid,0,'덮어쓰기','운영팀','실패해야함');
raise exception 'Stale edit accepted';
exception when serialization_failure then null;
end;
begin perform public.prayer_command(v,'unpublish');
raise exception 'Stale admin accepted';
exception when serialization_failure then null;
end;
select revision into v from public.match_control;
perform public.prayer_command(v,'draw');
begin perform public.prayer_command(v,'reset','{"confirm":"삭제"}');
raise exception 'Second admin accepted';
exception when serialization_failure then null;
end;
if (public.prayer_snapshot()->>'drawStartedAt') is null then raise exception 'Draw not shared';
end if;
if exists (select m.participant_id from public.match_members m join public.match_groups g on g.id=m.group_id where g.round_id=rid group by m.participant_id having count(*)>1) then raise exception 'Duplicate member';
end if;
end $$;
rollback;
select 'PASS: fixed groups, auto assignment, optimistic admin/edit locking, shared reveal;
rolled back' as result;
